package edu.kit.kastel.crownoffarmland.ui.renderer.board.boardsymbols;

/**
 * Defines positions relative to the selected field.
 *
 * @author ucgdi
 */
public enum SelectedRelative {
    /**
     * No relative position.
     */
    NONE,

    /**
     * Left of the selected field.
     */
    LEFT,

    /**
     * Right of the selected field.
     */
    RIGHT,

    /**
     * Above the selected field.
     */
    TOP,

    /**
     * Below the selected field.
     */
    BOTTOM,

    /**
     * Top left of the selected field.
     */
    TOP_LEFT,

    /**
     * Top right of the selected field.
     */
    TOP_RIGHT,

    /**
     * Bottom left of the selected field.
     */
    BOTTOM_LEFT,

    /**
     * Bottom right of the selected field.
     */
    BOTTOM_RIGHT
}