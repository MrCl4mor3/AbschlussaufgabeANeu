package edu.kit.kastel.crownoffarmland.gameplay.combat;

/**
 * Defines the possible types of duels.
 *
 * @author ucgdi
 */
public enum DuelType {
    /**
     * A duel involving a king.
     */
    KING,

    /**
     * A duel involving a blocking unit.
     */
    BLOCKADE,

    /**
     * A regular duel without special conditions.
     */
    STANDARD
}